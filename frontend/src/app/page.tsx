"use client";

import React, { useEffect, useRef } from 'react';

// ── Three.js top-view road background ────────────────────────────────────────
function RoadBackground() {
  const mountRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const el = mountRef.current;
    if (!el) return;

    const script = document.createElement('script');
    script.src = 'https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js';
    script.onload = () => init(el);
    document.head.appendChild(script);

    function init(container: HTMLElement) {
      const T = (window as any).THREE;
      let W = window.innerWidth;
      let H = window.innerHeight;

      // Renderer — alpha so page content shows through
      const renderer = new T.WebGLRenderer({ antialias: true, alpha: true });
      renderer.setSize(W, H);
      renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.5));
      renderer.shadowMap.enabled = true;
      container.appendChild(renderer.domElement);

      const scene = new T.Scene();

      // Top-down orthographic camera
      const cam = new T.OrthographicCamera(-W / 2, W / 2, H / 2, -H / 2, 1, 2000);
      cam.position.set(0, 800, 0);
      cam.lookAt(0, 0, 0);

      // Lighting
      scene.add(new T.AmbientLight(0xffffff, 0.9));
      const sun = new T.DirectionalLight(0xffffff, 0.5);
      sun.position.set(200, 800, 300);
      sun.castShadow = true;
      scene.add(sun);

      // ── Road surface (subtle asphalt) ─────────────────────────────────────
      const roadW = W * 2.5;
      const numLanes = 4;
      const laneH = 90;
      const roadH = numLanes * laneH;
      const roadY = -100; // slight offset from center

      const roadGeo = new T.PlaneGeometry(roadW, roadH);
      const roadMat = new T.MeshLambertMaterial({ color: 0xd1d5db, transparent: true, opacity: 0.18 });
      const road = new T.Mesh(roadGeo, roadMat);
      road.rotation.x = -Math.PI / 2;
      road.position.set(0, 0, roadY);
      scene.add(road);

      // Lane dividers (dashed lines)
      const dashMat = new T.MeshBasicMaterial({ color: 0x9ca3af, transparent: true, opacity: 0.35 });
      for (let l = 1; l < numLanes; l++) {
        const z = roadY - roadH / 2 + l * laneH;
        for (let x = -roadW / 2; x < roadW / 2; x += 90) {
          const dg = new T.PlaneGeometry(50, 3);
          const d = new T.Mesh(dg, dashMat);
          d.rotation.x = -Math.PI / 2;
          d.position.set(x, 0.5, z);
          scene.add(d);
        }
      }

      // Shoulder lines
      const shoulderMat = new T.MeshBasicMaterial({ color: 0xe5e7eb, transparent: true, opacity: 0.45 });
      [-roadH / 2, roadH / 2].forEach(dz => {
        const sg = new T.PlaneGeometry(roadW, 4);
        const sm = new T.Mesh(sg, shoulderMat);
        sm.rotation.x = -Math.PI / 2;
        sm.position.set(0, 0.5, roadY + dz);
        scene.add(sm);
      });

      // ── Truck builder (top-view) ──────────────────────────────────────────
      interface TruckMesh extends THREE.Group { _tireTrails: THREE.Mesh[]; }
      function makeTruck(color: number, sc: number) {
        const g = new T.Group() as TruckMesh;
        const bodyMat  = new T.MeshLambertMaterial({ color });
        const darkMat  = new T.MeshLambertMaterial({ color: darken(color, 0.4) });
        const glassMat = new T.MeshLambertMaterial({ color: 0x93c5fd, transparent: true, opacity: 0.7 });
        const tireMat  = new T.MeshLambertMaterial({ color: 0x1e293b });
        const rimMat   = new T.MeshLambertMaterial({ color: 0x94a3b8 });

        // Cargo body
        const bw = 36 * sc, bh = 10 * sc, bd = 60 * sc;
        const body = new T.Mesh(new T.BoxGeometry(bd, bh, bw), bodyMat);
        body.position.set(-8 * sc, bh / 2, 0);
        body.castShadow = true;
        g.add(body);

        // Body detail stripe
        const stripe = new T.Mesh(new T.BoxGeometry(bd - 4, bh + 0.5, 2 * sc), darkMat);
        stripe.position.set(-8 * sc, bh, 0);
        g.add(stripe);

        // Cabin (top view = shorter front block)
        const cw = 28 * sc, ch = 12 * sc, cd = 34 * sc;
        const cab = new T.Mesh(new T.BoxGeometry(cd, ch, cw), new T.MeshLambertMaterial({ color: darken(color, 0.15) }));
        cab.position.set(bd / 2 - 2 * sc, ch / 2, 0);
        cab.castShadow = true;
        g.add(cab);

        // Windshield (top-view glass)
        const wg = new T.Mesh(new T.BoxGeometry(cd * 0.5, 1, cw * 0.7), glassMat);
        wg.position.set(bd / 2 + 4 * sc, ch + 0.5, 0);
        g.add(wg);

        // Wheels — 6 total (top view: 3 left, 3 right)
        const tireR = 7 * sc, tireT = 5 * sc;
        const wheelPositions = [
          { x: -30 * sc, z:  cw / 2 + tireT / 2 },
          { x: 0,        z:  cw / 2 + tireT / 2 },
          { x:  28 * sc, z:  cw / 2 + tireT / 2 },
          { x: -30 * sc, z: -cw / 2 - tireT / 2 },
          { x: 0,        z: -cw / 2 - tireT / 2 },
          { x:  28 * sc, z: -cw / 2 - tireT / 2 },
        ];

        g._tireTrails = [];

        wheelPositions.forEach(({ x, z }) => {
          const tg = new T.Group();
          // Tire
          const tire = new T.Mesh(new T.CylinderGeometry(tireR, tireR, tireT, 12), tireMat);
          tire.rotation.x = Math.PI / 2;
          tg.add(tire);
          // Rim
          const rim = new T.Mesh(new T.CylinderGeometry(tireR * 0.55, tireR * 0.55, tireT + 0.3, 6), rimMat);
          rim.rotation.x = Math.PI / 2;
          tg.add(rim);
          // Hub bolt
          const hub = new T.Mesh(new T.CylinderGeometry(tireR * 0.15, tireR * 0.15, tireT + 0.5, 8), new T.MeshLambertMaterial({ color: 0xd1d5db }));
          hub.rotation.x = Math.PI / 2;
          tg.add(hub);

          tg.position.set(x, bh * 0.5, z);
          g.add(tg);

          // Tire trail plane (follows wheel, stays on road)
          const trailGeo = new T.PlaneGeometry(tireT * 0.7, 1);
          const trailMat = new T.MeshBasicMaterial({
            color: 0x374151, transparent: true, opacity: 0.22,
          });
          const trail = new T.Mesh(trailGeo, trailMat);
          trail.rotation.x = -Math.PI / 2;
          trail.position.set(0, 0.3, z);
          scene.add(trail);
          g._tireTrails.push(trail);
        });

        // Shadow disc
        const sdg = new T.CircleGeometry((bw / 2 + 6) * sc, 20);
        const sdm = new T.MeshBasicMaterial({ color: 0x000000, transparent: true, opacity: 0.07 });
        const sd = new T.Mesh(sdg, sdm);
        sd.rotation.x = -Math.PI / 2;
        sd.position.set(-8 * sc, -0.5, 0);
        g.add(sd);

        g._tireTrails = g._tireTrails;
        return g;
      }

      function darken(hex: number, f: number): number {
        const r = Math.floor(((hex >> 16) & 0xff) * (1 - f));
        const g = Math.floor(((hex >> 8) & 0xff) * (1 - f));
        const b = Math.floor((hex & 0xff) * (1 - f));
        return (r << 16) | (g << 8) | b;
      }

      // ── Tire mark trail system ────────────────────────────────────────────
      // We keep a pool of short mark quads that form rolling tire tracks
      const trailPool: {mesh: any; life: number; maxLife: number}[] = [];
      const trailMat = new T.MeshBasicMaterial({ color: 0x374151, transparent: true, opacity: 0.18, side: T.DoubleSide });

      function spawnTireMark(wx: number, wz: number, width: number) {
        const geo = new T.PlaneGeometry(width, 6);
        const m = new T.Mesh(geo, trailMat.clone());
        m.rotation.x = -Math.PI / 2;
        m.position.set(wx, 0.2, wz);
        scene.add(m);
        trailPool.push({ mesh: m, life: 1, maxLife: 1 });
      }

      // ── Fleet config ──────────────────────────────────────────────────────
      const fleetDefs = [
        { color: 0x2563eb, sc: 1.0,  spd: 1.4,  z: roadY - laneH * 1.5, startX: -W * 0.5 },
        { color: 0x16a34a, sc: 0.86, spd: 1.0,  z: roadY - laneH * 0.5, startX: -W * 0.8 },
        { color: 0xea580c, sc: 0.93, spd: 1.7,  z: roadY + laneH * 0.5, startX: -W * 1.2 },
        { color: 0x7c3aed, sc: 0.78, spd: 0.85, z: roadY + laneH * 1.5, startX: -W * 0.3 },
        { color: 0xd97706, sc: 0.95, spd: 2.1,  z: roadY - laneH * 1.0, startX: -W * 1.6 },
      ];

      const fleet = fleetDefs.map(def => {
        const truck = makeTruck(def.color, def.sc);
        truck.position.set(def.startX, 0, def.z);
        scene.add(truck);
        return { truck, ...def };
      });

      // ── Trail streak meshes (long horizontal tire streaks) ────────────────
      // Each truck has 2 continuous streak lines (left/right wheels)
      const trailStreaks: any[] = [];
      fleet.forEach(f => {
        const tw = 28 * f.sc;
        [-tw / 2 - 5, tw / 2 + 5].forEach(dz => {
          const sg = new T.PlaneGeometry(1, 4 * f.sc);
          const sm = new T.MeshBasicMaterial({ color: 0x374151, transparent: true, opacity: 0.15 });
          const s = new T.Mesh(sg, sm);
          s.rotation.x = -Math.PI / 2;
          scene.add(s);
          trailStreaks.push({ mesh: s, truck: f.truck, dz, truckDef: f });
        });
      });

      let frame = 0;
      let animId: number;
      function animate() {
        animId = requestAnimationFrame(animate);
        frame++;

        fleet.forEach(f => {
          f.truck.position.x += f.spd;
          if (f.truck.position.x > W + 400) f.truck.position.x = -W - 400;
        });

        // Update streak lengths/positions
        trailStreaks.forEach(s => {
          const tx = s.truck.position.x;
          const tz = s.truck.position.z + s.dz;
          // Stretch trail behind truck
          const trailLen = Math.min(Math.abs(tx + W), 300);
          s.mesh.scale.x = trailLen;
          s.mesh.position.set(tx - trailLen / 2, 0.2, tz);
        });

        // Spawn tire mark splats periodically
        if (frame % 6 === 0) {
          fleet.forEach(f => {
            const tw = 28 * f.sc;
            [-tw / 2 - 4, tw / 2 + 4].forEach(dz => {
              spawnTireMark(
                f.truck.position.x - 20,
                f.truck.position.z + dz,
                5 * f.sc,
              );
            });
          });
        }

        // Fade out old trail marks
        for (let i = trailPool.length - 1; i >= 0; i--) {
          const t = trailPool[i];
          t.life -= 0.012;
          (t.mesh.material as any).opacity = t.life * 0.18;
          if (t.life <= 0) {
            scene.remove(t.mesh);
            trailPool.splice(i, 1);
          }
        }

        renderer.render(scene, cam);
      }
      animate();

      // Resize
      const onResize = () => {
        W = window.innerWidth; H = window.innerHeight;
        renderer.setSize(W, H);
        cam.left = -W / 2; cam.right = W / 2;
        cam.top = H / 2; cam.bottom = -H / 2;
        cam.updateProjectionMatrix();
      };
      window.addEventListener('resize', onResize);

      (container as any)._cleanup3d = () => {
        cancelAnimationFrame(animId);
        window.removeEventListener('resize', onResize);
        renderer.dispose();
        if (container.contains(renderer.domElement)) container.removeChild(renderer.domElement);
      };
    }

    return () => {
      if ((el as any)._cleanup3d) (el as any)._cleanup3d();
    };
  }, []);

  return (
    <div
      ref={mountRef}
      style={{
        position: 'fixed', inset: 0, zIndex: 0,
        pointerEvents: 'none', overflow: 'hidden',
      }}
    />
  );
}

